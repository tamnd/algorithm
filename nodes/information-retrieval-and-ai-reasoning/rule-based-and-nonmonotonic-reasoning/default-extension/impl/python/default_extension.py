"""Brute-force search for the extensions of a finite propositional default theory.

A formula is a nested tuple: ("var", name), ("not", f), ("and", f, ...),
("or", f, ...), ("true",) or ("false",). A default alpha : beta_1, ..., beta_n / gamma
is a triple (alpha, [beta_1, ..., beta_n], gamma). A theory is (W, D).

A deductively closed theory over the given atoms is kept as its set of models:
a frozenset of the indices of the worlds that satisfy it. Th(S) contains phi
exactly when every model of S satisfies phi.

extensions(atom_names, W, D) tries each subset S of D, takes E = Th(W and the
conclusions of S) as a candidate, and keeps it when E is a fixed point of
Reiter's operator Gamma. Every extension is generated by a subset of D, so
none is missed. The cost is O(2^|D| |D|^2 2^n) formula evaluations for n atoms.
"""

from itertools import combinations, product
from typing import Dict, FrozenSet, List, Sequence, Tuple

Formula = tuple
Default = Tuple[Formula, Sequence[Formula], Formula]
Models = FrozenSet[int]


def evaluate(f: Formula, world: Dict[str, bool]) -> bool:
    op = f[0]
    if op == "var":
        return world[f[1]]
    if op == "not":
        return not evaluate(f[1], world)
    if op == "and":
        return all(evaluate(g, world) for g in f[1:])
    if op == "or":
        return any(evaluate(g, world) for g in f[1:])
    return op == "true"


def worlds(atom_names: Sequence[str]) -> List[Dict[str, bool]]:
    return [dict(zip(atom_names, v)) for v in product([False, True], repeat=len(atom_names))]


def models(formulas: Sequence[Formula], ws: List[Dict[str, bool]]) -> Models:
    """The models of a set of formulas, that is, the theory Th(formulas)."""
    return frozenset(i for i, w in enumerate(ws) if all(evaluate(f, w) for f in formulas))


def generating_defaults(theory: Tuple[Sequence[Formula], Sequence[Default]], e: Models, ws) -> FrozenSet[int]:
    """The least set G of defaults such that each prerequisite follows from W and cons(G) and each justification is consistent with e."""
    w_part, d_part = theory
    g: FrozenSet[int] = frozenset()  # @line L4
    while True:  # @line L5
        th = models(list(w_part) + [d_part[i][2] for i in g], ws)
        g2 = frozenset(
            i for i, (alpha, betas, _) in enumerate(d_part)
            if th <= models([alpha], ws) and all(e & models([b], ws) for b in betas)
        )  # @line L6
        if g2 == g:  # @line L7
            return g
        g = g2  # @line L8


def gamma(theory, e: Models, ws) -> Models:
    """Reiter's operator: Gamma(e) = Th(W and the conclusions of the defaults that e allows)."""
    w_part, d_part = theory
    g = generating_defaults(theory, e, ws)
    return models(list(w_part) + [d_part[i][2] for i in g], ws)


def extensions(atom_names: Sequence[str], w_part: Sequence[Formula], d_part: Sequence[Default]) -> List[Tuple[Models, FrozenSet[int]]]:
    """All extensions of (W, D), each as (models of E, generating defaults), in a fixed order."""
    ws = worlds(atom_names)
    theory = (list(w_part), list(d_part))
    found: Dict[Models, FrozenSet[int]] = {}  # @line L1
    for k in range(len(d_part) + 1):  # @line L2
        for s in combinations(range(len(d_part)), k):
            e = models(list(w_part) + [d_part[i][2] for i in s], ws)  # @line L3
            if e in found:
                continue
            g = generating_defaults(theory, e, ws)
            if models(list(w_part) + [d_part[i][2] for i in g], ws) == e:  # @line L9
                found[e] = g
    return sorted(found.items(), key=lambda item: sorted(item[1]))  # @line L10


def in_extension(e: Models, phi: Formula, atom_names: Sequence[str]) -> bool:
    """Whether the extension with the models e contains phi."""
    ws = worlds(atom_names)
    return all(evaluate(phi, ws[i]) for i in e)
