"""Regular two-level fractional factorial designs 2^(k-p).

Factors are capital letters. The first k - p letters are the base factors, which run
through a full 2^(k-p) factorial in standard order (A changes fastest). Each of the p
added factors is set to the product of a word of base factors, for example D = ABC.
An effect is a word (a set of letters); its column is the product of the factor columns.

The defining relation is the group of words generated by the p words "generator word
times added letter" (for D = ABC, the word ABCD), with the product of two words being
their symmetric difference. Two effects are aliased, so that their columns in the
fraction are equal or opposite, exactly when their product lies in the defining
relation. The resolution is the length of the shortest word, and the wordlength
pattern (A_3, A_4, ...) counts the words of each length; minimum aberration means
the lexicographically smallest pattern.
"""

from itertools import product
from string import ascii_uppercase


def word(s: str) -> frozenset[str]:
    """The set of letters of a word; 'I' (the identity) is the empty set."""
    return frozenset() if s == "I" else frozenset(s)


def name(w: frozenset[str]) -> str:
    return "".join(sorted(w)) or "I"


def design(k: int, generators: dict[str, str]) -> list[tuple[int, ...]]:
    """The 2^(k-p) runs as tuples of +-1, one entry per factor A, B, ..., in letter order."""
    letters = ascii_uppercase[:k]
    base = [c for c in letters if c not in generators]
    if len(base) != k - len(generators):
        raise ValueError("the generators must name added factors among the first k letters")
    runs = []
    for levels in product((-1, 1), repeat=len(base)):
        value = dict(zip(reversed(base), levels))  # A changes fastest: standard order
        for added, w in generators.items():
            if not set(w) <= set(base):
                raise ValueError("a generator word must use base factors only")
            v = 1
            for c in w:
                v *= value[c]
            value[added] = v
        runs.append(tuple(value[c] for c in letters))
    return runs


def defining_relation(generators: dict[str, str]) -> list[frozenset[str]]:
    """All 2^p - 1 words of the defining contrast subgroup, I excluded."""
    gens = [word(w) | {added} for added, w in generators.items()]
    group = {frozenset()}
    for g in gens:  # each word holds its own added letter, so the p words are independent
        group |= {h ^ g for h in group}
    return sorted(group - {frozenset()}, key=lambda w: (len(w), name(w)))


def alias_set(effect: str, relation: list[frozenset[str]]) -> list[str]:
    """The effects aliased with the given one: its products with every defining word."""
    e = word(effect)
    return [name(e ^ w) for w in relation]


def resolution(relation: list[frozenset[str]]) -> int:
    return min(len(w) for w in relation)


def wordlength_pattern(relation: list[frozenset[str]], k: int) -> tuple[int, ...]:
    """(A_3, A_4, ..., A_k): the number of defining words of each length."""
    return tuple(sum(len(w) == j for w in relation) for j in range(3, k + 1))


def column(runs: list[tuple[int, ...]], effect: str) -> list[int]:
    """The contrast column of an effect: the product of its factor columns."""
    idx = [ascii_uppercase.index(c) for c in word(effect)]
    out = []
    for r in runs:
        v = 1
        for i in idx:
            v *= r[i]
        out.append(v)
    return out


def estimate(runs: list[tuple[int, ...]], y: list[float], effect: str) -> float:
    """The usual effect estimate: mean response at + minus mean response at -."""
    col = column(runs, effect)
    return 2.0 * sum(c * v for c, v in zip(col, y)) / len(y)
