"""The Clifford group: how H, S and CNOT act on Pauli strings by conjugation.

A Pauli operator on n qubits is stored as (k, x, z): the operator
i^k * X^(x_{n-1}) Z^(z_{n-1}) (x) ... (x) X^(x_0) Z^(z_0), where x and z are n-bit integers
(bit j belongs to qubit j) and k is taken mod 4. A gate U acts on it by P -> U P U^dagger.
The rules are exact; no floating point is used. Qubit 0 is the least significant bit.

A circuit is a list of gates ("H", q), ("S", q) or ("CNOT", control, target).
Cost: O(1) word operations per gate and per Pauli, so O(n g) for the images of all 2n
generators X_j, Z_j under a circuit of g gates.
"""

from collections import deque

Pauli = tuple[int, int, int]  # (k, x, z)
Gate = tuple


def from_word(word: str, sign: int = 1) -> Pauli:
    """The Pauli string sign * word as (k, x, z). The rightmost letter acts on qubit 0."""
    x = z = 0
    ny = 0
    for q, c in enumerate(reversed(word)):
        if c in "XY":
            x |= 1 << q
        if c in "ZY":
            z |= 1 << q
        if c == "Y":
            ny += 1  # Y = i X Z
        if c not in "IXYZ":
            raise ValueError("letters must be I, X, Y or Z")
    k = (ny + (0 if sign == 1 else 2)) % 4
    return (k, x, z)


def to_word(p: Pauli, n: int) -> tuple[complex, str]:
    """(phase, word) with p = phase * word and the phase in {1, i, -1, -i}."""
    k, x, z = p
    letters = []
    ny = 0
    for q in range(n - 1, -1, -1):
        a, b = (x >> q) & 1, (z >> q) & 1
        letters.append("IZXY"[2 * a + b])
        ny += a & b
    phase = [1, 1j, -1, -1j][(k - ny) % 4]  # X Z = -i Y
    return phase, "".join(letters)


def conjugate_gate(g: Gate, p: Pauli) -> Pauli:
    """U p U^dagger for one gate U."""
    k, x, z = p
    if g[0] == "H":
        q = g[1]
        a, b = (x >> q) & 1, (z >> q) & 1
        k += 2 * (a & b)  # H (XZ) H = Z X = -X Z
        x = (x & ~(1 << q)) | (b << q)
        z = (z & ~(1 << q)) | (a << q)
    elif g[0] == "S":
        q = g[1]
        a = (x >> q) & 1
        k += a  # S X S^dagger = Y = i X Z
        z ^= a << q
    elif g[0] == "CNOT":
        c, t = g[1], g[2]
        x ^= ((x >> c) & 1) << t  # X_c -> X_c X_t
        z ^= ((z >> t) & 1) << c  # Z_t -> Z_c Z_t
    else:
        raise ValueError("unknown gate")
    return (k % 4, x, z)


def conjugate(circuit: list[Gate], p: Pauli) -> Pauli:
    """U p U^dagger where U is the circuit (its first gate acts first)."""
    for g in circuit:
        p = conjugate_gate(g, p)
    return p


def tableau(circuit: list[Gate], n: int) -> tuple[Pauli, ...]:
    """The images of X_0, Z_0, X_1, Z_1, ..., X_{n-1}, Z_{n-1}. They fix the circuit up to a global phase."""
    out = []
    for j in range(n):
        out.append(conjugate(circuit, (0, 1 << j, 0)))
        out.append(conjugate(circuit, (0, 0, 1 << j)))
    return tuple(out)


def commute(p: Pauli, q: Pauli) -> bool:
    """True if the two Pauli operators commute (symplectic product 0)."""
    s = bin((p[1] & q[2]) ^ (p[2] & q[1])).count("1")
    return s % 2 == 0


def clifford_group_order(n: int) -> int:
    """|C_n / U(1)| = 2^(n^2 + 2n) * prod_{j=1..n} (4^j - 1)."""
    r = 1 << (n * n + 2 * n)
    for j in range(1, n + 1):
        r *= 4 ** j - 1
    return r


def generators(n: int) -> list[Gate]:
    gens: list[Gate] = []
    for q in range(n):
        gens += [("H", q), ("S", q)]
    for c in range(n):
        for t in range(n):
            if c != t:
                gens.append(("CNOT", c, t))
    return gens


def enumerate_tableaux(n: int) -> dict:
    """Breadth-first search over the group generated by H, S and CNOT, modulo global phase.

    Each element is stored as its tableau; the value is a shortest circuit that gives it.
    """
    start = tableau([], n)
    seen = {start: []}
    queue = deque([start])
    gens = generators(n)
    while queue:
        t = queue.popleft()
        for g in gens:
            u = tuple(conjugate_gate(g, p) for p in t)
            if u not in seen:
                seen[u] = seen[t] + [g]
                queue.append(u)
    return seen
