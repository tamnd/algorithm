"""Feldman (1987) and Pedersen (1991) verifiable secret sharing.

Both add public commitments to Shamir's scheme over Z_q, in a group of prime
order q generated by g:

  Feldman:  C_j = g^{a_j}               (perfectly binding; reveals g^s)
  Pedersen: C_j = g^{a_j} h^{b_j}       (perfectly hiding; binding if log_g h is unknown)

Party i checks its share against prod_j C_j^{i^j}. The file also has the
joint-Feldman distributed key generation (Pedersen's DKG) and the bias attack
of Gennaro, Jarecki, Krawczyk and Rabin, run on a toy group against local
simulated parties.

The groups here are tiny, so discrete logarithms are easy and everybody knows
log_g h. For study only. The code is not constant time and must not be used to
protect real data. Use a reviewed threshold library built on libsodium or a
FIPS 140 validated module.
"""

import secrets
from dataclasses import dataclass


@dataclass(frozen=True)
class Group:
    p: int          # safe prime p = 2q + 1
    g: int          # generator of the subgroup of order q
    h: int          # second generator; log_g h must be unknown to the dealer

    @property
    def q(self):
        return (self.p - 1) // 2


TINY = Group(23, 4, 9)           # q = 11, log_4 9 = 8
TOY = Group(2039, 4, 9)          # q = 1019


def poly_eval(coeffs, x, q):
    y = 0
    for c in reversed(coeffs):
        y = (y * x + c) % q
    return y


def expected_commitment(commitments, i, G):
    """prod_j C_j^{i^j} mod p."""
    acc, e = 1, 1
    for c in commitments:
        acc = acc * pow(c, e, G.p) % G.p
        e = e * i % G.q
    return acc


# ------------------------------------------------------------ Feldman
def feldman_deal(s, t, n, G, rand=None):
    rand = rand or (lambda: secrets.randbelow(G.q))
    coeffs = [s % G.q] + [rand() for _ in range(t - 1)]           # @line L1
    commitments = [pow(G.g, a, G.p) for a in coeffs]              # @line L2
    shares = {i: poly_eval(coeffs, i, G.q) for i in range(1, n + 1)}  # @line L3
    return commitments, shares


def feldman_verify(i, share, commitments, G):
    return pow(G.g, share, G.p) == expected_commitment(commitments, i, G)  # @line L4


# ------------------------------------------------------------ Pedersen
def pedersen_deal(s, t, n, G, rand=None):
    rand = rand or (lambda: secrets.randbelow(G.q))
    a = [s % G.q] + [rand() for _ in range(t - 1)]
    b = [rand() for _ in range(t)]
    commitments = [pow(G.g, x, G.p) * pow(G.h, y, G.p) % G.p for x, y in zip(a, b)]
    shares = {i: (poly_eval(a, i, G.q), poly_eval(b, i, G.q)) for i in range(1, n + 1)}
    return commitments, shares


def pedersen_verify(i, share, commitments, G):
    s_i, r_i = share
    lhs = pow(G.g, s_i, G.p) * pow(G.h, r_i, G.p) % G.p
    return lhs == expected_commitment(commitments, i, G)


# ------------------------------------------------------------ reconstruction
def lagrange_at_zero(xs, q):
    out = []
    for j, xj in enumerate(xs):
        num, den = 1, 1
        for m, xm in enumerate(xs):
            if m != j:
                num = num * xm % q
                den = den * (xm - xj) % q
        out.append(num * pow(den, -1, q) % q)
    return out


def reconstruct(shares, t, verify):
    """Keep the shares that verify and interpolate any t of them."""
    good = [(i, s) for i, s in shares.items() if verify(i, s)]    # @line L5
    if len(good) < t:
        return None
    good = good[:t]
    q = verify.q
    lams = lagrange_at_zero([i for i, _ in good], q)
    value = lambda s: s[0] if isinstance(s, tuple) else s
    return sum(l * value(s) for l, (_, s) in zip(lams, good)) % q  # @line L6


class Verifier:
    """A callable share check that also carries q, for reconstruct()."""

    def __init__(self, commitments, G, pedersen=False):
        self.commitments, self.G, self.pedersen = commitments, G, pedersen
        self.q = G.q

    def __call__(self, i, share):
        check = pedersen_verify if self.pedersen else feldman_verify
        return check(i, share, self.commitments, self.G)


def complaints(commitments, shares, G, pedersen=False):
    """The parties whose private share fails the check; they would complain."""
    v = Verifier(commitments, G, pedersen)
    return [i for i, s in shares.items() if not v(i, s)]


def brute_force_secret(c0, G):
    """Feldman leaks g^s: in a toy group, search for s."""
    for s in range(G.q):
        if pow(G.g, s, G.p) == c0:
            return s
    return None


# ------------------------------------------------------------ DKG
def joint_feldman(n, t, G, rand, cheat=None):
    """Each party deals a Feldman sharing of a random z_i. Parties whose
    sharing fails are disqualified. `cheat(broadcasts)` may return a set of
    corrupt dealers that choose, after seeing every commitment, to be
    disqualified (by sending one bad share). Returns (qualified, y, x_shares)."""
    dealings = {i: feldman_deal(rand(), t, n, G, rand) for i in range(1, n + 1)}
    drop = cheat({i: d[0] for i, d in dealings.items()}) if cheat else set()
    for i in drop:
        commitments, shares = dealings[i]
        shares[1] = (shares[1] + 1) % G.q        # one bad share draws a complaint
    qual = [i for i, (c, sh) in dealings.items() if not complaints(c, sh, G)]
    y = 1
    for i in qual:
        y = y * dealings[i][0][0] % G.p
    x_shares = {j: sum(dealings[i][1][j] for i in qual) % G.q for j in range(1, n + 1)}
    return qual, y, x_shares


def bias_attack(corrupt, predicate, G):
    """The GJKR attack: drop the corrupt dealer if that makes predicate(y) true."""
    def cheat(broadcast):
        y_all = 1
        for c in broadcast.values():
            y_all = y_all * c[0] % G.p
        if predicate(y_all):
            return set()
        y_without = y_all * pow(broadcast[corrupt][0], -1, G.p) % G.p
        return {corrupt} if predicate(y_without) else set()
    return cheat
