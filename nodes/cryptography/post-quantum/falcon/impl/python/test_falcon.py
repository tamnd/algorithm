def test_kat_copy_is_exact():
    assert hashlib.sha256(bytes.fromhex(KAT_PK)).hexdigest() == KAT_PK_SHA256
    assert hashlib.sha256(bytes.fromhex(KAT_SM)).hexdigest() == KAT_SM_SHA256


def test_kat_count0_verifies():
    pk, sm = bytes.fromhex(KAT_PK), bytes.fromhex(KAT_SM)
    assert len(pk) == 897 and len(sm) == 691
    assert verify_kat_sm(pk, sm) == bytes.fromhex(KAT_MSG)


def test_kat_changed_message_or_signature_fails():
    pk, sm = bytes.fromhex(KAT_PK), bytearray(bytes.fromhex(KAT_SM))
    msg_at = 42
    changed = bytearray(sm)
    changed[msg_at] ^= 1
    assert verify_kat_sm(pk, bytes(changed)) is None
    changed = bytearray(sm)
    changed[200] ^= 0x10  # inside the compressed s2
    assert verify_kat_sm(pk, bytes(changed)) is None


def test_public_key_range():
    h = decode_public_key(bytes.fromhex(KAT_PK))
    assert len(h) == 512 and all(0 <= x < Q for x in h)


def test_hash_to_point_is_uniform_enough():
    c = hash_to_point(b"x" * 40, 512)
    assert len(c) == 512 and all(0 <= x < Q for x in c)
    mean = sum(c) / 512
    assert abs(mean - (Q - 1) / 2) < 600


def test_compress_round_trip_and_minus_zero():
    rng = random.Random(5)
    s = [round(rng.gauss(0, 165)) for _ in range(512)]
    data = compress(s, 625)
    assert decompress(data, 512) == s
    # sign bit 1 with value 0 ("minus zero") must be rejected
    bad = bytes([0b10000000, 0b10000000]) + bytes(10)
    assert decompress(bad, 1) is None


def test_beta_matches_sigma():
    for n, (b2, sigma, _) in OFFICIAL.items():
        assert b2 == math.floor((1.1 * sigma) ** 2 * 2 * n)


def test_toy_key_equation_and_signatures():
    toy = ToyFalcon(16, random.Random(2024))
    f, g, F, G = toy.f, toy.g, toy.F, toy.G
    lhs = [a - b for a, b in zip(poly_mul(f, G), poly_mul(g, F))]
    assert lhs == [Q] + [0] * 15  # f G - g F = q
    assert poly_mul(f, toy.h, Q) == [x % Q for x in g]  # h = g / f mod q
    for i in range(5):
        msg = b"message %d" % i
        sig = toy.sign(msg)
        assert toy.verify(msg, sig)
        assert not toy.verify(msg + b"!", sig)
        nonce, s2 = sig
        assert not toy.verify(msg, (nonce, [s2[0] + 200] + s2[1:]))
