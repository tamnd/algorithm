def test_acvp_keygen():
    sizes = {"ML-DSA-44": (1312, 2560), "ML-DSA-65": (1952, 4032), "ML-DSA-87": (2592, 4896)}
    for tc, name, seed, pk_sha, sk_sha in KEYGEN_VECTORS:
        pk, sk = keygen_internal(bytes.fromhex(seed), name)
        assert (len(pk), len(sk)) == sizes[name], tc
        assert hashlib.sha256(pk).hexdigest() == pk_sha, tc
        assert hashlib.sha256(sk).hexdigest() == sk_sha, tc


def test_acvp_siggen_deterministic_44():
    sk = bytes.fromhex(SIG_SK_HEX)
    assert hashlib.sha256(sk).hexdigest() == SIG_SK_SHA256  # the copy is exact
    sig = sign(sk, bytes.fromhex(SIG_MSG), bytes.fromhex(SIG_CTX), "ML-DSA-44", deterministic=True)
    assert len(sig) == 2420
    assert hashlib.sha256(sig).hexdigest() == SIG_SHA256


def test_sign_verify_and_forgeries_fail():
    pk, sk = keygen_internal(bytes(32), "ML-DSA-44")
    msg = b"attack at dawn"
    sig = sign(sk, msg, b"ctx")
    assert verify(pk, msg, sig, b"ctx")
    assert not verify(pk, b"attack at dusk", sig, b"ctx")
    assert not verify(pk, msg, sig, b"other context")
    bad = bytearray(sig)
    bad[100] ^= 4  # a change inside z
    assert not verify(pk, msg, bytes(bad), b"ctx")
    bad = bytearray(sig)
    bad[0] ^= 1  # a change in the challenge hash
    assert not verify(pk, msg, bytes(bad), b"ctx")
    pk2, _ = keygen_internal(bytes([1]) * 32, "ML-DSA-44")
    assert not verify(pk2, msg, sig, b"ctx")


def test_hedged_signatures_differ_deterministic_repeat():
    pk, sk = keygen_internal(bytes([7]) * 32, "ML-DSA-44")
    a = sign(sk, b"m", deterministic=True)
    b = sign(sk, b"m", deterministic=True)
    c = sign(sk, b"m")
    assert a == b
    assert a != c
    assert verify(pk, b"m", c)


def test_rounding_identities():
    gamma2 = PARAMS["ML-DSA-44"][6]
    for r in list(range(0, Q, 4099)) + [0, 1, Q - 1, Q - 2, 2 * gamma2, Q - 1 - gamma2]:
        r1, r0 = power2round(r)
        assert r1 * 8192 + r0 == r and -4096 < r0 <= 4096
        h1, l0 = decompose(r, gamma2)
        assert (h1 * 2 * gamma2 + l0) % Q == r
        assert 0 <= h1 < 44


def test_hint_recovers_high_bits():
    # UseHint(MakeHint(z, r), r) = HighBits(r + z) when |z| <= gamma2 (FIPS 204, Section 7.4)
    gamma2 = PARAMS["ML-DSA-44"][6]
    for r in range(0, Q, 7919):
        for z in (-gamma2, -1234, 0, 1, 5000, gamma2):
            h = make_hint(z % Q, r, gamma2)
            assert use_hint(h, r, gamma2) == decompose(r + z, gamma2)[0]


def test_other_parameter_sets_round_trip():
    pk, sk = keygen("ML-DSA-65")
    sig = sign(sk, b"x", name="ML-DSA-65")
    assert len(sig) == 3309 and verify(pk, b"x", sig, name="ML-DSA-65")
