@pytest.mark.parametrize("name,ent,nonce,pers,add1,out1,ent_r,add_r,add2,out2", KAT)
def test_known_answers(name, ent, nonce, pers, add1, out1, ent_r, add_r, add2, out2):
    d = DualEC(h(ent), h(nonce), h(pers), hash_name=name)
    assert d.generate(30, h(add1)).hex() == out1
    d.reseed(h(ent_r), h(add_r))
    assert d.generate(30, h(add2)).hex() == out2


