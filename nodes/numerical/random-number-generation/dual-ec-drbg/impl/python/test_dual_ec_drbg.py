def test_curve_and_points():
    assert on_curve(P_POINT) and on_curve(Q_POINT)
    assert P_POINT == (GX, GY)
    assert scalar_mult(ORDER, P_POINT) is None
    assert scalar_mult(ORDER, Q_POINT) is None  # Q lies in the prime-order group generated by P
    assert scalar_mult(ORDER - 1, P_POINT) == (GX, PRIME - GY)
    a, b = 0x1234567890ABCDEF, 0xFEDCBA987654321
    assert scalar_mult(a, scalar_mult(b, P_POINT)) == scalar_mult(a * b, P_POINT)
    assert lift_x(GX) in (P_POINT, (GX, PRIME - GY))
    assert lift_x(0) is None or on_curve(lift_x(0))


def test_generate_matches_definition():
    d = DualEC(bytes(range(16)), bytes(8))
    s0 = d.s
    out = d.generate(45)  # two blocks, the second truncated
    s1 = scalar_mult(s0, P_POINT)[0]
    s2 = scalar_mult(s1, P_POINT)[0]
    r1 = scalar_mult(s1, Q_POINT)[0] % 2 ** OUTLEN
    r2 = scalar_mult(s2, Q_POINT)[0] % 2 ** OUTLEN
    assert out == (r1.to_bytes(30, "big") + r2.to_bytes(30, "big"))[:45]
    assert d.s == scalar_mult(s2, P_POINT)[0]  # the final update of SP 800-90A
    assert d.reseed_counter == 2


def _backdoored(seed: bytes):
    d_secret = int.from_bytes(hashlib.sha256(seed).digest(), "big") % ORDER
    Q = scalar_mult(d_secret, P_POINT)
    return Q, pow(d_secret, -1, ORDER)  # P = e * Q


def test_shumow_ferguson_state_recovery():
    Q, e = _backdoored(b"backdoor")
    g = DualEC(bytes(range(16)), bytes(range(16, 24)), Q=Q)
    s0 = g.s
    out = g.generate(150)  # five blocks in one request
    s1 = scalar_mult(s0, P_POINT)[0]
    hi = scalar_mult(s1, Q)[0] >> OUTLEN  # the 16 hidden bits, used only to keep the search short
    window = range(max(0, hi - 40), min(2 ** 16, hi + 40))
    found = recover_state(e, out[:30], out[30:32], P_POINT, Q, window)
    assert len(found) == 1
    # 32 observed bytes give every later block of the request
    assert predict_blocks(found[0], 4, P_POINT, Q) == out[30:150]


def test_trapdoor_needs_e():
    Q, e = _backdoored(b"backdoor")
    g = DualEC(bytes(range(16)), bytes(range(16, 24)), Q=Q)
    s1 = scalar_mult(g.s, P_POINT)[0]
    out = g.generate(60)
    hi = scalar_mult(s1, Q)[0] >> OUTLEN
    window = range(max(0, hi - 40), min(2 ** 16, hi + 40))
    assert recover_state(e + 1, out[:30], out[30:32], P_POINT, Q, window) == []


def test_reseed_counter_counts_blocks():
    d = DualEC(bytes(16), reseed_interval=3)
    d.generate(60)
    d.generate(30)
    with pytest.raises(ReseedRequired):
        d.generate(1)
    d.reseed(bytes(range(16)))
    assert len(d.generate(90)) == 90
    with pytest.raises(ValueError):
        DualEC(bytes(15))


def test_byte_frequencies_chi_square():
    # 8190 bytes (273 blocks); chi-square with 255 degrees of freedom, 0.999 quantile 330.52.
    # This finds nothing: the known bias of the 240-bit truncation is far too small for a test of this size.
    d = DualEC(bytes(range(16)), bytes(8))
    data = d.generate(8190)
    counts = [0] * 256
    for byte in data:
        counts[byte] += 1
    e = len(data) / 256
    chi2 = sum((c - e) ** 2 / e for c in counts)
    assert chi2 < 330.52
