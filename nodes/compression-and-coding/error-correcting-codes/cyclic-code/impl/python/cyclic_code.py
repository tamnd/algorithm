"""Binary cyclic codes as ideals of GF(2)[x]/(x^n - 1).

A polynomial over GF(2) is a Python int: bit i is the coefficient of x^i.
A word (c_0, ..., c_{n-1}) is the polynomial c_0 + c_1 x + ... + c_{n-1} x^{n-1}.
"""


def deg(a: int) -> int:
    """Degree of a; the zero polynomial has degree -1."""
    return a.bit_length() - 1


def pmul(a: int, b: int) -> int:
    """Carry-less product of two GF(2) polynomials."""
    out = 0
    while b:
        if b & 1:
            out ^= a
        a <<= 1
        b >>= 1
    return out


def pdivmod(a: int, b: int) -> tuple[int, int]:
    """Quotient and remainder of a by b over GF(2)."""
    if b == 0:
        raise ZeroDivisionError("division by the zero polynomial")
    q, db = 0, deg(b)
    while deg(a) >= db:
        s = deg(a) - db
        q ^= 1 << s
        a ^= b << s
    return q, a


def is_generator(g: int, n: int) -> bool:
    """True when g divides x^n - 1, so g generates a cyclic code of length n."""
    return g != 0 and pdivmod((1 << n) | 1, g)[1] == 0


def check_polynomial(g: int, n: int) -> int:
    """h(x) = (x^n - 1) / g(x)."""
    h, r = pdivmod((1 << n) | 1, g)
    if r:
        raise ValueError("g does not divide x^n - 1")
    return h


def cyclic_shift(c: int, n: int) -> int:
    """x c(x) mod (x^n - 1): (c_0, ..., c_{n-1}) -> (c_{n-1}, c_0, ..., c_{n-2})."""
    top = (c >> (n - 1)) & 1
    return ((c << 1) & ((1 << n) - 1)) | top


def encode_nonsystematic(m: int, g: int) -> int:
    """c(x) = m(x) g(x)."""
    return pmul(m, g)


def encode_systematic(m: int, k: int, g: int) -> int:
    """c(x) = x^r m(x) + (x^r m(x) mod g(x)), with r = deg g.

    The remainder is computed by the r-bit division register that also
    computes a CRC: the message bits enter from the highest power down.
    The message sits in positions r .. r + k - 1, the check bits in 0 .. r - 1.
    """
    r = deg(g)
    low = g & ((1 << r) - 1)  # g without its x^r term
    reg = 0
    for i in range(k - 1, -1, -1):
        fb = ((reg >> (r - 1)) & 1) ^ ((m >> i) & 1)
        reg = (reg << 1) & ((1 << r) - 1)
        if fb:
            reg ^= low
    return (m << r) | reg


def syndrome(v: int, g: int) -> int:
    """s(x) = v(x) mod g(x); zero exactly for codewords."""
    return pdivmod(v, g)[1]


def generator_rows(g: int, n: int) -> list[int]:
    """The rows g(x), x g(x), ..., x^{k-1} g(x) of a generator matrix."""
    k = n - deg(g)
    return [g << i for i in range(k)]


def parity_check_rows(g: int, n: int) -> list[int]:
    """Rows of a parity-check matrix: the shifts x^i h*(x), with h* the reciprocal of h."""
    h = check_polynomial(g, n)
    k = deg(h)
    hrev = int(format(h, f"0{k + 1}b")[::-1], 2)
    return [hrev << i for i in range(n - k)]


def codewords(g: int, n: int) -> list[int]:
    """All 2^k codewords m(x) g(x) with deg m < k."""
    k = n - deg(g)
    return [pmul(m, g) for m in range(1 << k)]


def zeros(g: int, m: int, prim: int) -> list[int]:
    """The exponents j in [0, 2^m - 2] with g(alpha^j) = 0 in GF(2^m).

    alpha is a root of the primitive polynomial prim (given with its x^m term).
    For n = 2^m - 1 these are the zeros of the cyclic code generated by g.
    """
    def fmul(a: int, b: int) -> int:
        out = 0
        while b:
            if b & 1:
                out ^= a
            b >>= 1
            a <<= 1
            if a >> m:
                a ^= prim
        return out

    n = (1 << m) - 1
    out, beta = [], 1  # beta = alpha^j
    for j in range(n):
        y = 0
        for i in range(deg(g), -1, -1):  # Horner's rule
            y = fmul(y, beta) ^ ((g >> i) & 1)
        if y == 0:
            out.append(j)
        beta = fmul(beta, 2)
    return out


def divisors_of_xn1(n: int) -> list[int]:
    """All monic divisors of x^n - 1 over GF(2) (by trial, for small n)."""
    f = (1 << n) | 1
    return [g for g in range(1, 1 << (n + 1)) if pdivmod(f, g)[1] == 0]
